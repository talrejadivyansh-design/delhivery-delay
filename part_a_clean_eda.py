import numpy as np
import pandas as pd
import os
from src.shipment_prep import clean_shipments, build_features , FEATURES
raw = pd.read_csv("data/raw_shipments.csv")
hubs = pd.read_csv("data/hubs.csv")
df, medians = clean_shipments(raw)
df = build_features(df, hubs)
df["is_delayed"] = (df["delivery_hours"] > df["promised_hours"]).astype(int)
df.to_csv("data/modelling_table.csv", index=False)
os.makedirs("outputs",exist_ok=True)
dedup = raw.drop_duplicates()
missing = dedup.isnull().sum()
checks = {}
checks["raw_rows"] = len(raw)
checks["duplicate_rows_removed"] = len(raw) - len(dedup)
checks["rows_after_dedup"] = len(dedup)
checks["missing_distance_km_before"] = int(missing["distance_km"])
checks["missing_parcel_weight_before"] = int(missing["parcel_weight_kg"])
checks["missing_declared_value_before"] = int(missing["declared_value"])
checks["missing_payment_mode_before"] = int(missing["payment_mode"])
checks["sentinel_weight_rows"] = len(dedup[dedup["parcel_weight_kg"]>100])
checks["median_distance_km"] = round(medians["distance_km"], 4)
checks["median_parcel_weight_kg"] = round(medians["parcel_weight_kg"], 4)
checks["median_declared_value_inr"] = round(medians["declared_value_inr"], 4)
checks["service_type_spellings_before"] = int(dedup["service_type"].nunique())
checks["service_type_spellings_after"] = int(df["service_type"].nunique())
checks["rows_after_hub_merge"] = len(df)
checks["nulls_in_features_and_target"] = int(df[FEATURES + ["delivery_hours", "is_delayed"]].isnull().sum().sum())
checks["delayed_count"] = int(df["is_delayed"].sum())
checks["delay_rate"] = round(df["is_delayed"].mean(), 4)
checks["declared_value_mean_inr"] = round(df["declared_value_inr"].mean(), 4)
checks["declared_value_median_inr"] = round(df["declared_value_inr"].median(), 4)
checks["log_declared_value_mean"] = round(df["log_declared_value"].mean(), 4)
checks["log_declared_value_median"] = round(df["log_declared_value"].median(), 4)
q1 = np.percentile(df["delivery_hours"],25)
q3 = np.percentile(df["delivery_hours"],75)
iqr = q3-q1
lower = q1 - 1.5*iqr
upper = q3 + 1.5*iqr
checks["hours_q1"] = round(q1,4)
checks["hours_q3"] = round(q3,4)
checks["hours_lower_bound"] = round(lower,4)
checks["hours_upper_bound"] = round(upper,4)
checks["hours_outlier_count"] = int(((df["delivery_hours"]<lower)|(df["delivery_hours"]>upper)).sum())
pd.DataFrame({"metric": list(checks.keys()), "value": list(checks.values())}).to_csv("outputs/part_a_checks.csv", index=False)
print(checks)
df["distance_band"] = pd.cut(df["distance_km"], bins = [0,200,400,600,2000], labels = ["0-200","201-400","401-600","601+" ])
t1 = df.groupby("service_type")["is_delayed"].agg(["count","sum","mean"])
t1["mean_hours"] = df.groupby("service_type")["delivery_hours"].mean()
t1 = t1.reset_index()
t1.columns = ["group","shipments","delayed","delay_rate","mean_hours"]
t1.insert(0,"dimension","service_type")
t2 = df.groupby("hub_tier")["is_delayed"].agg(["count","sum","mean"])
t2["mean_hours"] = df.groupby("hub_tier")["delivery_hours"].mean()
t2 = t2.reset_index()
t2.columns = ["group","shipments","delayed","delay_rate","mean_hours"]
t2.insert(0,"dimension","hub_tier")
t3 = df.groupby("distance_band")["is_delayed"].agg(["count","sum","mean"])
t3["mean_hours"] = df.groupby("distance_band")["delivery_hours"].mean()
t3 = t3.reset_index()
t3.columns = ["group","shipments","delayed","delay_rate","mean_hours"] 
t3.insert(0,"dimension","distance_band")
delay_by_group = pd.concat([t1,t2,t3],ignore_index= True)
delay_by_group["group"] = delay_by_group["group"].astype(str)
delay_by_group = delay_by_group.round(4)
delay_by_group.to_csv("outputs/part_a_delay_by_group.csv", index=False)
print(delay_by_group)
corr = df.corr(numeric_only = True).round(4)
corr.to_csv("outputs/part_a_correlations.csv")
print(corr["delivery_hours"].sort_values(ascending=False))